#!/usr/bin/env python3
"""Write the Android AppFunctions metadata XML (platform v1 format) for the tools of a running Unisono MCP endpoint.

Usage:
  scripts/new-appfunctions-xml.py <mcp-url> <output.xml>

Each tool becomes one <appfunction> whose function_id is the tool name, which is what UnisonoAppFunctionService
dispatches on. The v1 format carries no parameter schema; the description and parameter names are written as a
comment for people reading the file. Standard library only.
"""
import sys
import xml.sax.saxutils as sx
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mcp_call import Client  # noqa: E402


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__)
        return 2
    client = Client(argv[1])
    client.request("initialize", {"protocolVersion": "2025-06-18", "capabilities": {},
                                  "clientInfo": {"name": "new-appfunctions-xml", "version": "0"}})
    client.notify("notifications/initialized")
    tools = client.request("tools/list")["tools"]
    client.close()
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- Generated by scripts/new-appfunctions-xml.py from the tools of a running Unisono registry. -->',
             '<!-- Platform v1 format: the system indexes function ids; parameters are read at run time by name. -->',
             '<appfunctions>']
    for t in tools:
        params = ", ".join((t.get("inputSchema") or {}).get("properties", {}).keys())
        lines.append(f'  <!-- {sx.escape(t.get("description", "").strip())} Parameters: {params or "none"} -->')
        lines.append('  <appfunction>')
        lines.append(f'    <function_id>{sx.escape(t["name"])}</function_id>')
        lines.append('    <enabled_by_default>true</enabled_by_default>')
        lines.append('  </appfunction>')
    lines.append('</appfunctions>')
    Path(argv[2]).write_text("\n".join(lines) + "\n")
    print(f"wrote {argv[2]} with {len(tools)} functions")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
